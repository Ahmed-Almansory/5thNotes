function gradeIds(ids, pre) {
  let ok = 0, bad = 0, n = 0;
  const y = scrollY;
  ids.forEach(id => {
    const q = byId(id), l = PX[id];
    if (!q || !l) return;
    const wasWrong = P[id] && P[id].r === 0;
    const r = q.a ? (isOk(q, l) ? 1 : 0) : 2;
    P[id] = { c: l, r: r };
    recordWC(id, wasWrong);
    if (wasWrong) RTS.add(id);
    SESS.add(id);
    delete PX[id];
    n++;
    if (r === 1) ok++; else if (r === 0) bad++;
  });
  save(); savePX();
  if (!pendScope().length) stopTimer();
  let gradedInPlace = true;
  ids.forEach(gid => { if (!refreshCard(gid)) gradedInPlace = false; });
  if (!gradedInPlace) { render(); scrollTo(0, y); }
  stat();
  toast((pre || '') + 'Graded ' + n + ' · ✓ ' + ok + ' correct · ✗ ' + bad + ' wrong');
}

