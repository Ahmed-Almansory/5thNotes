// Keep the tapped card glued to its viewport position across a full
// re-render. render() rebuilds the whole list, and off-screen cards
// collapse to their content-visibility intrinsic-size estimate, so
// restoring the old absolute scrollY points at the wrong content and
// the card jumps off-screen (first answer after scrolling down).
// The card's position only settles once the browser re-renders the
// near-viewport cards, so anchor after layout settles (next frames),
// re-checking in case the correction itself brings new cards into range.
function rerenderKeep(id, y0, top0) {
  render();
  const el = document.getElementById('q-' + id);
  if (!el || top0 == null) { scrollTo(0, y0); return; }
  const nextFrame = typeof requestAnimationFrame === 'function'
    ? cb => requestAnimationFrame(cb)
    : cb => setTimeout(cb, 0);
  let n = 0;
  const fix = () => {
    const cur = document.getElementById('q-' + id);
    if (!cur) return;
    const dy = cur.getBoundingClientRect().top - top0;
    if (Math.abs(dy) > 1) scrollTo({ top: scrollY + dy, behavior: 'instant' });
    if (++n < 3 && Math.abs(dy) > 1) nextFrame(fix);
  };
  nextFrame(fix);
}

