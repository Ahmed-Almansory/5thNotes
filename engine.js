function helpText(k) {
  if (k == 'shuffle') {
    const inCat = cur && cur !== 'all' && cur !== '__notes';
    return inCat ? HELP.shuffleCat : (CATS.length ? HELP.shuffleAll : HELP.shuffleAllPlain);
  }
  if (k.indexOf('cat:') == 0) {
    const c = CATS.find(x => x.id == k.slice(4));
    if (!c) return '';
    return c.description || (/zanqa/i.test(c.id) ? HELP.zanqa : /hawary/i.test(c.id) ? HELP.hawary : 'An additional view of existing questions. Progress is shared with the main bank.');
  }
  return HELP[k] || '';
}

function hideTip() {
  tipEl.style.display = 'none';
  if (tipFor) { tipFor.classList.remove('on'); tipFor = null; }
  clearTimeout(tipT);
}

function showTip(el, hov) {
  const s = helpText(el.dataset.h);
  if (!s) return;
  hideTip();
  tipEl.textContent = s;
  tipEl.style.display = 'block';
  const r = el.getBoundingClientRect(), w = tipEl.offsetWidth, h = tipEl.offsetHeight;
  tipEl.style.left = Math.min(Math.max(8, r.left + r.width / 2 - w / 2), innerWidth - w - 8) + 'px';
  let y = r.bottom + 8;
  if (y + h > innerHeight - 8) y = Math.max(8, r.top - h - 8);
  tipEl.style.top = y + 'px';
  tipFor = el;
  tipHov = !!hov;
  el.classList.add('on');
  if (!hov) tipT = setTimeout(hideTip, 9000);
}

document.addEventListener('click', e => {
  const i = e.target.closest('.hi');
  if (i) {
    e.preventDefault();
    e.stopPropagation();
    if (tipFor === i && !tipHov) hideTip(); else showTip(i, false);
    return;
  }
  if (tipFor) hideTip();
}, true);

document.addEventListener('keydown', e => {
  const i = e.target.closest && e.target.closest('.hi');
  if (i && (e.key == 'Enter' || e.key == ' ')) { e.preventDefault(); i.click(); }
  else if (e.key == 'Escape') hideTip();
});

