/* Distractor strikethrough: right-click on desktop, long-press on touch.
   iOS Safari never fires contextmenu on buttons, so a touch timer handles
   it; Android fires contextmenu AND the touch timer for one press, so
   toggleStrike ignores a second toggle from the OTHER source within 700ms
   of the first — two toggles from the same source (e.g. two right-clicks)
   still work. */
function toggleStrike(opt, src) {
  if (!opt || opt.classList.contains('ok') || opt.classList.contains('bad')) return;
  const now = Date.now();
  if (opt._struckAt && now - opt._struckAt < 700 && opt._struckBy && opt._struckBy !== src) return;
  opt._struckAt = now;
  opt._struckBy = src;
  opt.classList.toggle('struck');
}
$('list').addEventListener('contextmenu', e => {
  const opt = e.target.closest('.opt');
  if (!opt) return;
  e.preventDefault();
  toggleStrike(opt, 'menu');
});
